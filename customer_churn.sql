SELECT COUNT(*) AS TOTAL_ROWS
FROM TELCO_CHURN_RAW;
SELECT CHURN, COUNT(*) AS CUSTOMER_COUNT
FROM TELCO_CHURN_RAW
GROUP BY CHURN;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT_IF(TOTALCHARGES IS NULL) AS MISSING_TOTAL_CHARGES,
    COUNT_IF(TENURE IS NULL) AS MISSING_TENURE,
    COUNT_IF(CHURN IS NULL) AS MISSING_CHURN
FROM TELCO_CHURN_RAW;
CREATE OR REPLACE TABLE TELCO_CHURN_CLEAN AS
SELECT
    CUSTOMERID,
    GENDER,
    SENIORCITIZEN,
    PARTNER,
    DEPENDENTS,
    TENURE,
    PHONESERVICE,
    MULTIPLELINES,
    INTERNETSERVICE,
    ONLINESECURITY,
    ONLINEBACKUP,
    DEVICEPROTECTION,
    TECHSUPPORT,
    STREAMINGTV,
    STREAMINGMOVIES,
    CONTRACT,
    PAPERLESSBILLING,
    PAYMENTMETHOD,
    MONTHLYCHARGES,
    TRY_TO_DOUBLE(NULLIF(TRIM(TOTALCHARGES), '')) AS TOTALCHARGES,
    IFF(CHURN = 'Yes', 1, 0) AS CHURN
FROM TELCO_CHURN_RAW
WHERE CHURN IN ('Yes', 'No');
SELECT *
FROM TELCO_CHURN_CLEAN
LIMIT 10;





